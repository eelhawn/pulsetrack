#!/usr/bin/env python3
"""Regenerate src/css/10-pt-neat-borders.css, the part of the Neater look that removes outlines.

Run it after adding a feature that draws its own bordered cards:   python3 tools/neat_borders.py
It opens the built page, finds every style rule (outside the neater look itself) whose border uses the
theme's border greys (--z700 / --z800, solid or dashed), and writes one rule per selector that swaps the
outline for the neater look's softer colour. State styles (selected, on, active) keep working because the
rules are written with :where(), which adds no specificity.
"""
import os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tests'))
from common import ROOT, page

SKIP = ['.pt-range', '.pt-dot', '.pt-note-line', '.pt-tip-plain', '.pt-st-lines', '#session-stopwatch-badge', '#pt-checkin', '.pt-fc-card',
        '.pt-co-pick', '.pt-co-kind', '.pt-sw-row', '.pt-wk-ex', '.pt-ladder', '.pt-tier', '.pt-pc-row']
JS = '''() => {
  const out = [];
  for (const ss of document.styleSheets) {
    let rules; try { rules = ss.cssRules; } catch (e) { continue; }
    const own = (ss.ownerNode && ss.ownerNode.id) || "";
    if (own === "tailwind-css" || own === "pt-fonts" || own.startsWith("pt-neat")) continue;
    const walk = rs => { for (const r of rs) {
      if (r.cssRules && !r.selectorText) { walk(r.cssRules); continue; }
      if (!r.style || !r.selectorText) continue;
      const all = ["border", "border-color"].map(k => r.style.getPropertyValue(k)).join(" ");
      const sides = ["border-top", "border-bottom", "border-left", "border-right"].map(k => r.style.getPropertyValue(k)).join(" ");
      if ((/var\\(--z[78]/.test(all) || /dashed/.test(all)) && !/var\\(--a/.test(all)) out.push([r.selectorText, /dashed/.test(all), r.style.getPropertyPriority("border") === "important" || r.style.getPropertyPriority("border-color") === "important"]);
    } };
    walk(rules);
  }
  return out;
}'''


def split_top(sel):
    parts, depth, cur = [], 0, ''
    for ch in sel:
        if ch in '([': depth += 1
        if ch in ')]': depth -= 1
        if ch == ',' and depth == 0:
            parts.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip(): parts.append(cur.strip())
    return parts


def main():
    with page() as p:
        found = p.evaluate(JS)
    card, ctl, dashed, imp = [], [], [], []
    seen = set()
    for sel, dash, important in found:
        for one in split_top(sel):
            if one in seen or any(s in one for s in SKIP):
                continue
            seen.add(one)
            if important:
                imp.append(one)      # written again below with !important, because the original wins otherwise
                continue
            (ctl if re.search(r'\b(input|select|textarea)\b|\[type=|\.pt-sin\b', one) else card).append(one)
            if dash: dashed.append(one)
    pre = ':where(html[data-neat="1"]) '
    def block(sels, decl):
        return ',\n'.join(pre + s for s in sels) + ' {\n  ' + decl + '\n}\n' if sels else ''
    out = ['/* Generated by tools/neat_borders.py: do not edit by hand. The Neater look swaps card and control outlines for softer ones. */\n']
    out.append(block(card, 'border-color: var(--nt-hair);'))
    out.append(block(ctl, 'border-color: var(--nt-edge);'))
    out.append(block(dashed, 'border-style: solid;'))
    out.append(block(imp, 'border-color: var(--nt-hair) !important;'))
    path = os.path.join(ROOT, 'src', 'css', '10-pt-neat-borders.css')
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write('\n'.join(out))
    print('wrote %s: %d card rules, %d control rules, %d dashed, %d important' % (os.path.relpath(path, ROOT), len(card), len(ctl), len(dashed), len(imp)))


if __name__ == '__main__':
    main()
