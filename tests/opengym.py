"""2.96.0 openGym exercise library: loaded in the background, searchable in the picker after PulseTrack's own, the openGym chip pages through
the library, picking one makes it a normal exercise (and it stays one after a restart), PulseTrack's own exercises win, the licence is shipped."""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import Checks, page

c = Checks('opengym')
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHOTS = '/tmp/claude-0/-home-claude/395da5c4-9b49-54b4-93e4-f9926c59aa1c/scratchpad/'

# ---------------------------------------------------------------- the file and the licence
src = open(os.path.join(ROOT, 'opengym-exercises.js'), encoding='utf-8').read()
L = json.loads(src[src.index('['):src.rindex(']') + 1])
c.ok(len(L) > 5000, 'the file has the library (%d exercises)' % len(L))
c.eq(len({e['og'] for e in L}), len(L), 'one entry per openGym id')
c.eq(len({e['name'].lower() for e in L}), len(L), 'no name twice')
c.ok(all(e.get('desc') and e.get('tips') and e.get('muscle') and e.get('category') and e.get('eq') for e in L), 'every entry has a description, steps, muscle, category and equipment')
c.ok(not re.search(r'\.(webp|mp4|gif|png|jpe?g)\b', src), 'no pictures or animations are referenced')
own = open(os.path.join(ROOT, 'exercises.js'), encoding='utf-8').read()
names = {m.lower() for m in re.findall(r'^\s*\{ name: "([^"]+)"', own, re.M)}
c.eq([e['name'] for e in L if e['name'].lower() in names], [], 'none of PulseTrack\'s own exercises is in it twice')
c.ok(os.path.exists(os.path.join(ROOT, 'LICENSE')) and 'GNU AFFERO GENERAL PUBLIC LICENSE' in open(os.path.join(ROOT, 'LICENSE')).read(), 'the AGPL licence is in the repo')
notice = open(os.path.join(ROOT, 'NOTICE.md'), encoding='utf-8').read()
c.ok('openGym' in notice and 'ExerciseDB' in notice and 'Gym visual' in notice, 'NOTICE.md credits openGym and ExerciseDB and says the media are not included')
c.ok("'./opengym-exercises.js'" in open(os.path.join(ROOT, 'sw.js')).read(), 'the service worker saves it for offline')

# ---------------------------------------------------------------- the picker
for w in (390, 360):
    with page(w=w, h=800) as p:
        c.eq(p.evaluate('() => typeof OPENGYM_EXERCISES'), 'undefined', '%dpx: not loaded at start-up (the app opens as fast as before)' % w)
        p.evaluate('() => PT.og.load()')
        p.wait_for_function('() => PT.og.list().length > 5000', timeout=15000)
        n0 = p.evaluate('() => EXERCISE_DATABASE.length')
        c.eq(p.evaluate('() => EXERCISE_DATABASE.some(e => e.og)'), False, '%dpx: loading adds nothing to your list by itself' % w)
        p.evaluate('() => { const pr = app.data.programs.find(x => x.id === "my_6day_chest_back_legs_sharms"); app.selectProgram(pr, null, true); app.activeProgram = pr; app.activeDay = pr.days[0]; app.showView("workout"); }')
        p.evaluate('() => app.openExerciseSelector("add")')
        p.wait_for_timeout(200)
        p.fill('#ex-search-input', 'zercher')
        p.wait_for_timeout(250)
        heads = p.evaluate('() => [...document.querySelectorAll("#ex-list-container .sticky span:first-child")].map(s => s.textContent.trim())')
        c.ok('openGym library' in heads, '%dpx: searching "zercher" shows an openGym library heading' % w)
        c.ok(heads.index('openGym library') == len(heads) - 1, '%dpx: after PulseTrack\'s own results' % w)
        og = p.evaluate('() => [...document.querySelectorAll(".pt-og-results [data-og]")].map(b => b.querySelector("span span").textContent)')
        c.ok(len(og) >= 2 and all('zercher' in x.lower() for x in og), '%dpx: its matches are zercher lifts (%d)' % (w, len(og)))
        c.ok(p.evaluate('() => !!document.querySelector(".pt-og-credit")'), '%dpx: with the openGym credit line' % w)
        p.fill('#ex-search-input', 'curl')
        p.wait_for_timeout(250)
        c.eq(p.evaluate('() => document.querySelectorAll(".pt-og-results [data-og]").length'), 60, '%dpx: a big search shows the first 60' % w)
        p.click('.pt-og-results .pt-og-more')
        c.eq(p.evaluate('() => document.querySelectorAll(".pt-og-results [data-og]").length'), 120, '%dpx: Show more adds 60' % w)
        # the chip
        p.fill('#ex-search-input', '')
        p.wait_for_timeout(200)
        c.ok(p.evaluate('() => !!document.querySelector("[data-og-chip]")'), '%dpx: an openGym chip' % w)
        c.ok(p.evaluate('() => /Search [56],\\d{3} exercises/.test(document.getElementById("ex-search-input").placeholder)'), '%dpx: the search box counts the library too' % w)
        p.evaluate('() => document.querySelector("[data-og-chip]").click()')
        p.wait_for_timeout(250)
        c.eq(p.evaluate('() => document.querySelectorAll("#ex-list-container [data-og]").length'), 100, '%dpx: it lists the library 100 at a time' % w)
        c.ok(p.evaluate('() => document.querySelector("[data-og-chip]").classList.contains("bg-emerald-500") && document.querySelectorAll("#ex-chips .bg-emerald-500").length === 1'), '%dpx: the chip is the one lit' % w)
        c.ok(p.evaluate('() => document.documentElement.scrollWidth <= innerWidth + 1'), '%dpx: no sideways scroll' % w)
        if w == 390: p.screenshot(path=SHOTS + 'opengym390.png')
        p.click('#ex-list-container .pt-og-more')
        c.eq(p.evaluate('() => document.querySelectorAll("#ex-list-container [data-og]").length'), 200, '%dpx: Show more' % w)
        # pick one
        p.fill('#ex-search-input', 'zercher')
        p.wait_for_timeout(250)
        name = p.evaluate('() => document.querySelector(".pt-og-results [data-og] span span").textContent')
        before = p.evaluate('() => app.activeDay.exercises.length')
        p.evaluate('() => document.querySelector(".pt-og-results [data-og]").click()')
        p.wait_for_timeout(300)
        c.eq(p.evaluate('() => app.activeDay.exercises.length'), before + 1, '%dpx: picking it adds it to the workout' % w)
        c.eq(p.evaluate('(n) => app.activeDay.exercises.some(e => e.name === n)', name), True, '%dpx: under its name' % w)
        e = p.evaluate('(n) => { const e = EXERCISE_DATABASE.find(x => x.name === n); return e && [!!e.og, !!e.desc, (e.tips || []).length > 2, e.muscle]; }', name)
        c.ok(e and e[0] and e[1] and e[2] and e[3], '%dpx: and it is now in your list with its muscle, description and steps' % w)
        c.eq(p.evaluate('() => EXERCISE_DATABASE.length'), n0 + 1, '%dpx: only that one was added' % w)
        cue = p.evaluate('(n) => { const h = PT.cuesHtml(n, true); const d = document.createElement("div"); d.innerHTML = h; return [d.querySelectorAll("li").length, d.textContent.includes("Avoid:"), PT.cueFor(n).do[0] === PT.og.get(n).tips[0]]; }', name)
        c.eq(cue, [len(p.evaluate('(n) => PT.og.get(n).tips', name)), False, True], '%dpx: Form tips shows its own steps (and no empty Avoid line)' % w)
        c.eq(p.evaluate('(n) => PT.category(n)', name), p.evaluate('(n) => PT.og.get(n).category', name), '%dpx: the app files it under its body part' % w)
        p.evaluate('() => document.getElementById("ex-search-input").dispatchEvent(new Event("input"))')
        c.eq(p.evaluate('(n) => [...document.querySelectorAll(".pt-og-results [data-og]")].some(b => b.textContent.includes(n))', name), False, '%dpx: it is not offered twice' % w)
        # after a restart it is still a normal exercise (it is in the workout)
        p.evaluate('() => { WorkoutStorage.setData(app.data); }')
        p.reload(); p.wait_for_function('() => window.app && app.dom', timeout=10000)
        p.evaluate('() => PT.og.load()')
        p.wait_for_function('() => PT.og.list().length > 5000', timeout=15000)
        c.eq(p.evaluate('(n) => EXERCISE_DATABASE.some(x => x.name === n && x.og)', name), True, '%dpx: after closing and reopening it is still in your list' % w)
        c.eq(p.errors, [], '%dpx: no page errors' % w)

c.done()
